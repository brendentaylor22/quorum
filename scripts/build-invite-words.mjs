#!/usr/bin/env node
/**
 * Regenerate `apps/api/src/invite-words.ts` from the EFF large wordlist.
 *
 * The list is vendored rather than fetched at runtime or installed as a
 * dependency: invite entropy must not depend on the network being up or on a
 * transitive package changing its contents under us. Run this only to adopt a
 * new upstream revision, and read the diff before committing it — the file it
 * writes is load-bearing for how guessable an invite link is.
 *
 *   node scripts/build-invite-words.mjs [path-to-eff_large_wordlist.txt]
 *
 * With no argument it downloads the list from eff.org.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE_URL =
  'https://www.eff.org/files/2016/07/18/eff_large_wordlist.txt';
const output = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../apps/api/src/invite-words.ts',
);

const [, , localPath] = process.argv;
const raw =
  localPath === undefined
    ? await fetch(SOURCE_URL).then(async (response) => {
        if (!response.ok) {
          throw new Error(`EFF wordlist fetch failed: ${response.status}`);
        }
        return response.text();
      })
    : readFileSync(localPath, 'utf8');

// Each upstream line is "11111\tabacus": a dice numeral, a tab, the word.
const words = raw
  .trim()
  .split('\n')
  .map((line) => line.split('\t')[1]?.trim() ?? '')
  // A phrase joins its words with hyphens, so a word containing one would make
  // the word count ambiguous to anyone retyping the link.
  .filter((word) => /^[a-z]+$/u.test(word));

if (words.length < 7000) {
  throw new Error(`Refusing to write a ${words.length}-word list`);
}
if (new Set(words).size !== words.length) {
  throw new Error('Upstream list contains duplicates');
}

const bitsPerWord = Math.log2(words.length);
const chunks = [];
for (let index = 0; index < words.length; index += 10) {
  chunks.push(words.slice(index, index + 10).join(' '));
}

const header = `/**
 * Word list for invite phrases: the EFF "large" diceware list.
 *
 * Chosen over a general dictionary because it is built for exactly this job:
 * common words, no profanity, no two words sharing their first three letters,
 * and nothing homophonic enough to mistype from dictation. That is what lets a
 * spoken invite link survive the trip across a room.
 *
 * The four hyphenated entries of the published list ("drop-down", "felt-tip",
 * "t-shirt", "yo-yo") are dropped, because a phrase joins its own words with
 * hyphens. Losing four of 7776 costs 0.0007 bits per word.
 *
 * Source: ${SOURCE_URL}
 * EFF large wordlist by Joseph Bonneau, Electronic Frontier Foundation,
 * licensed CC BY 3.0. Reformatted only: dice numerals stripped and hyphenated
 * entries removed. The words themselves are unchanged.
 *
 * Generated by scripts/build-invite-words.mjs. Do not edit by hand.
 */

const WORDS = [
${chunks.map((chunk) => `  '${chunk}',`).join('\n')}
].join(' ');

/** ${words.length.toString()} words: ${bitsPerWord.toFixed(3)} bits of entropy per word. */
export const INVITE_WORDS: readonly string[] = Object.freeze(WORDS.split(' '));
`;

writeFileSync(output, header);
console.log(
  `${output}: ${words.length.toString()} words, ` +
    `${bitsPerWord.toFixed(3)} bits/word`,
);
